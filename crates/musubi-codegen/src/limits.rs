//! Fixed versioned resource limits and downward-only manifest overrides.

use serde::{Deserialize, Serialize};

/// Normative hard limits for config-v4 contract and typed-data inputs.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
pub struct HardLimits {
    /// Manifest bytes.
    pub manifest_bytes: usize,
    /// Aggregate bytes loaded from every contract input.
    pub aggregate_input_bytes: usize,
    /// One ABI input size.
    pub abi_bytes: usize,
    /// One creation or runtime bytecode input size.
    pub bytecode_bytes: usize,
    /// One AST input size.
    pub ast_bytes: usize,
    /// One metadata or storage-layout input size.
    pub auxiliary_bytes: usize,
    /// Contract entries.
    pub contracts: usize,
    /// One typed-data schema input size.
    pub typed_data_schema_bytes: usize,
    /// One typed-data vector input size.
    pub typed_data_vector_bytes: usize,
    /// Typed-data entries.
    pub typed_data_entries: usize,
    /// Types and roots for one typed-data entry.
    pub typed_data_types: usize,
    /// Vectors for one typed-data entry.
    pub typed_data_vectors: usize,
    /// Aggregate fields for one typed-data entry.
    pub typed_data_fields: usize,
    /// ABI entries for one contract.
    pub abi_items: usize,
    /// Aggregate nested components for one ABI.
    pub abi_components: usize,
    /// Maximum cumulative ABI fixed-array element product along one type path.
    pub abi_fixed_array_elements: usize,
    /// Recursive tuple/array nesting.
    pub nesting: usize,
    /// Maximum cumulative typed-data fixed-array element product along one type path.
    pub typed_data_fixed_array_elements: usize,
    /// AST nodes for one contract.
    pub ast_nodes: usize,
    /// UTF-8 bytes in an identifier.
    pub identifier_bytes: usize,
    /// Generated files.
    pub generated_files: usize,
    /// Aggregate generated bytes.
    pub generated_bytes: usize,
}

impl HardLimits {
    /// Immutable versioned maxima from the accepted architecture.
    pub const V1: Self = Self {
        manifest_bytes: 1024 * 1024,
        aggregate_input_bytes: 128 * 1024 * 1024,
        abi_bytes: 8 * 1024 * 1024,
        bytecode_bytes: 2 * 1024 * 1024,
        ast_bytes: 32 * 1024 * 1024,
        auxiliary_bytes: 16 * 1024 * 1024,
        contracts: 256,
        typed_data_schema_bytes: 8 * 1024 * 1024,
        typed_data_vector_bytes: 16 * 1024 * 1024,
        typed_data_entries: 256,
        typed_data_types: 4_096,
        typed_data_vectors: 4_096,
        typed_data_fields: 65_536,
        abi_items: 4_096,
        abi_components: 65_536,
        abi_fixed_array_elements: musubi_core::ABI_FIXED_ARRAY_ELEMENTS_LIMIT,
        nesting: 64,
        typed_data_fixed_array_elements: 65_536,
        ast_nodes: 500_000,
        identifier_bytes: 256,
        generated_files: 10_000,
        generated_bytes: 256 * 1024 * 1024,
    };

    /// Applies only lower, non-zero limits.
    ///
    /// # Errors
    ///
    /// Returns a field name if an override is zero or exceeds the normative maximum.
    pub fn with_overrides(overrides: &LimitOverrides) -> Result<Self, &'static str> {
        let mut limits = Self::V1;
        macro_rules! lower {
            ($field:ident) => {
                if let Some(value) = overrides.$field {
                    if value == 0 || value > limits.$field {
                        return Err(stringify!($field));
                    }
                    limits.$field = value;
                }
            };
        }
        lower!(aggregate_input_bytes);
        lower!(abi_bytes);
        lower!(bytecode_bytes);
        lower!(ast_bytes);
        lower!(auxiliary_bytes);
        lower!(contracts);
        lower!(typed_data_schema_bytes);
        lower!(typed_data_vector_bytes);
        lower!(typed_data_entries);
        lower!(typed_data_types);
        lower!(typed_data_vectors);
        lower!(typed_data_fields);
        lower!(abi_items);
        lower!(abi_components);
        lower!(abi_fixed_array_elements);
        lower!(nesting);
        lower!(typed_data_fixed_array_elements);
        lower!(ast_nodes);
        lower!(identifier_bytes);
        lower!(generated_files);
        lower!(generated_bytes);
        Ok(limits)
    }
}

/// Optional downward-only resource-limit overrides in a versioned manifest.
#[derive(Clone, Debug, Default, Eq, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LimitOverrides {
    /// Lower aggregate input byte limit.
    pub aggregate_input_bytes: Option<usize>,
    /// Lower one-ABI byte limit.
    pub abi_bytes: Option<usize>,
    /// Lower bytecode-file byte limit.
    pub bytecode_bytes: Option<usize>,
    /// Lower AST byte limit.
    pub ast_bytes: Option<usize>,
    /// Lower metadata/layout byte limit.
    pub auxiliary_bytes: Option<usize>,
    /// Lower contract-count limit.
    pub contracts: Option<usize>,
    /// Lower one-typed-data-schema byte limit.
    pub typed_data_schema_bytes: Option<usize>,
    /// Lower one-typed-data-vector byte limit.
    pub typed_data_vector_bytes: Option<usize>,
    /// Lower typed-data-entry limit.
    pub typed_data_entries: Option<usize>,
    /// Lower per-entry typed-data type and root limit.
    pub typed_data_types: Option<usize>,
    /// Lower per-entry typed-data vector limit.
    pub typed_data_vectors: Option<usize>,
    /// Lower per-entry aggregate typed-data field limit.
    pub typed_data_fields: Option<usize>,
    /// Lower ABI-item limit.
    pub abi_items: Option<usize>,
    /// Lower ABI-component limit.
    pub abi_components: Option<usize>,
    /// Lower cumulative ABI fixed-array element-product limit.
    pub abi_fixed_array_elements: Option<usize>,
    /// Lower nesting limit.
    pub nesting: Option<usize>,
    /// Lower cumulative typed-data fixed-array element-product limit.
    pub typed_data_fixed_array_elements: Option<usize>,
    /// Lower AST-node limit.
    pub ast_nodes: Option<usize>,
    /// Lower identifier byte limit.
    pub identifier_bytes: Option<usize>,
    /// Lower generated-file limit.
    pub generated_files: Option<usize>,
    /// Lower generated-byte limit.
    pub generated_bytes: Option<usize>,
}
