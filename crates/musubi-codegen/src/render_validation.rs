//! Fail-closed validation for publicly mutable generation IR before rendering.

use musubi_core::{ArtifactKind, CreationBytecode, FixedBytes, RuntimeBytecode, sha256};

use crate::{
    ContractIr, Diagnostic, DiagnosticCode, GenerationIr, RenderError, abi_parse::parse_abi,
    name_validation::validate_generated_names, owned_identity::OwnedTypeRegistry,
};

pub(crate) fn validate(
    ir: &GenerationIr,
    generator: &musubi_core::GeneratorInfo,
) -> Result<(), RenderError> {
    validate_limits(ir)?;
    validate_file_count(ir)?;
    if ir.contracts.len() > ir.limits.contracts
        || ir.typed_data.len() > ir.limits.typed_data_entries
    {
        return Err(invalid("generation IR exceeds its effective entry limits"));
    }
    for contract in &ir.contracts {
        validate_contract(contract, ir)?;
    }
    for typed in &ir.typed_data {
        let fields = typed
            .types
            .iter()
            .try_fold(0_usize, |count, item| count.checked_add(item.fields.len()));
        if typed.types.len() > ir.limits.typed_data_types
            || typed.roots.len() > ir.limits.typed_data_types
            || fields.is_none_or(|count| count > ir.limits.typed_data_fields)
        {
            return Err(invalid("typed-data IR exceeds its effective limits"));
        }
    }
    crate::snapshot_validation::validate_with_limits(
        &crate::build_snapshot(ir, generator),
        ir.limits,
    )
    .map_err(|_| invalid("generation IR failed semantic validation"))
}

fn validate_contract(contract: &ContractIr, ir: &GenerationIr) -> Result<(), RenderError> {
    // Canonical ABI is a generated asset: pretty printing may exceed the raw input byte cap.
    // The tree also charges this asset against the aggregate output budget during insertion.
    if contract.canonical_abi.len() > ir.limits.generated_bytes {
        return Err(resource_limit(
            "canonical ABI exceeds the generated byte limit",
        ));
    }
    let values =
        crate::abi_json::parse(&contract.canonical_abi, ir.limits).map_err(|diagnostic| {
            if diagnostic.code == DiagnosticCode::LimitExceeded {
                RenderError { diagnostic }
            } else {
                invalid("canonical ABI is not valid unique-key ABI JSON")
            }
        })?;
    let canonical = crate::canonical::canonical_abi(&values)
        .map_err(|_| invalid("canonical ABI cannot be serialized"))?;
    let abi = parse_abi(&values, ir.limits).map_err(|_| invalid("canonical ABI is invalid"))?;
    if canonical != contract.canonical_abi
        || sha256(&canonical) != contract.canonical_abi_sha256
        || abi != contract.abi
        || !nonzero(&contract.raw_abi_sha256)
    {
        return Err(invalid("contract ABI identity is inconsistent"));
    }
    validate_capability(contract, ir.limits)?;
    validate_digests(contract)?;
    let owned_types = OwnedTypeRegistry::build(&contract.abi, &contract.enrichments, ir.limits)
        .map_err(|_| invalid("contract owned-type IR is invalid"))?;
    validate_generated_names(
        &contract.id,
        contract.kind,
        &contract.abi,
        &contract.enrichments,
        &owned_types,
    )
    .map_err(|_| invalid("contract generated names are invalid"))?;
    if owned_types != contract.owned_types
        || owned_types.enrichment_count() != contract.enrichments.len()
    {
        return Err(invalid("contract owned-type IR identity is inconsistent"));
    }
    Ok(())
}

fn validate_capability(
    contract: &ContractIr,
    limits: crate::HardLimits,
) -> Result<(), RenderError> {
    match contract.kind {
        ArtifactKind::Deployable => {
            let creation = contract
                .creation
                .as_ref()
                .ok_or_else(|| invalid("deployable IR has no creation bytecode"))?;
            if creation.template.len() > limits.bytecode_bytes {
                return Err(invalid("creation bytecode exceeds the effective limit"));
            }
            CreationBytecode::new(creation.template.clone(), creation.links.clone())
                .map_err(|_| invalid("creation bytecode IR is invalid"))?;
            if let Some(runtime) = &contract.runtime {
                if runtime.template.len() > limits.bytecode_bytes {
                    return Err(invalid("runtime bytecode exceeds the effective limit"));
                }
                RuntimeBytecode::new(
                    runtime.template.clone(),
                    runtime.links.clone(),
                    runtime.immutables.clone(),
                )
                .map_err(|_| invalid("runtime bytecode IR is invalid"))?;
            }
        }
        ArtifactKind::Interface
            if contract.creation.is_some()
                || contract.runtime.is_some()
                || contract.abi.constructor.is_some()
                || contract.auxiliary_digests.storage_layout.is_some() =>
        {
            return Err(invalid("interface IR contains deployment-only data"));
        }
        ArtifactKind::Interface => {}
    }
    Ok(())
}

fn validate_digests(contract: &ContractIr) -> Result<(), RenderError> {
    if [
        contract.auxiliary_digests.ast,
        contract.auxiliary_digests.metadata,
        contract.auxiliary_digests.storage_layout,
    ]
    .into_iter()
    .flatten()
    .all(|digest| nonzero(&digest))
    {
        Ok(())
    } else {
        Err(invalid("contract provenance contains a zero digest"))
    }
}

fn validate_limits(ir: &GenerationIr) -> Result<(), RenderError> {
    let limits = ir.limits;
    let maximum = crate::HardLimits::V1;
    let valid = [
        (limits.manifest_bytes, maximum.manifest_bytes),
        (limits.aggregate_input_bytes, maximum.aggregate_input_bytes),
        (limits.abi_bytes, maximum.abi_bytes),
        (limits.bytecode_bytes, maximum.bytecode_bytes),
        (limits.ast_bytes, maximum.ast_bytes),
        (limits.auxiliary_bytes, maximum.auxiliary_bytes),
        (limits.contracts, maximum.contracts),
        (
            limits.typed_data_schema_bytes,
            maximum.typed_data_schema_bytes,
        ),
        (
            limits.typed_data_vector_bytes,
            maximum.typed_data_vector_bytes,
        ),
        (limits.typed_data_entries, maximum.typed_data_entries),
        (limits.typed_data_types, maximum.typed_data_types),
        (limits.typed_data_vectors, maximum.typed_data_vectors),
        (limits.typed_data_fields, maximum.typed_data_fields),
        (limits.abi_items, maximum.abi_items),
        (limits.abi_components, maximum.abi_components),
        (
            limits.abi_fixed_array_elements,
            maximum.abi_fixed_array_elements,
        ),
        (limits.nesting, maximum.nesting),
        (
            limits.typed_data_fixed_array_elements,
            maximum.typed_data_fixed_array_elements,
        ),
        (limits.ast_nodes, maximum.ast_nodes),
        (limits.identifier_bytes, maximum.identifier_bytes),
        (limits.generated_files, maximum.generated_files),
        (limits.generated_bytes, maximum.generated_bytes),
    ]
    .into_iter()
    .all(|(value, bound)| value > 0 && value <= bound);
    if valid {
        Ok(())
    } else {
        Err(invalid("generation IR has invalid effective limits"))
    }
}

fn nonzero(value: &FixedBytes<32>) -> bool {
    value.as_ref().iter().any(|byte| *byte != 0)
}

fn invalid(message: &str) -> RenderError {
    RenderError {
        diagnostic: Diagnostic::error(DiagnosticCode::InconsistentArtifact, message),
    }
}

/// Rejects an impossible owner inventory before allocating leaf source or layout metadata.
fn validate_file_count(ir: &GenerationIr) -> Result<(), RenderError> {
    let mut files = 4_usize; // Marker, Cargo manifest, crate root, release record.
    for contract in &ir.contracts {
        let owners = [
            4, // Contract facade, types facade, artifact, ABI asset.
            contract.abi.functions.len(),
            contract.abi.events.len(),
            contract.abi.errors.len(),
            contract.enrichments.len(),
            contract.owned_types.tuples().count(),
            usize::from(contract.kind == ArtifactKind::Deployable),
            usize::from(contract.creation.is_some()),
            usize::from(contract.runtime.is_some()),
        ];
        for count in owners {
            files = files
                .checked_add(count)
                .ok_or_else(|| resource_limit("generated file count overflowed"))?;
        }
    }
    for typed in &ir.typed_data {
        files = files
            .checked_add(2)
            .and_then(|value| value.checked_add(typed.types.len()))
            .ok_or_else(|| resource_limit("generated file count overflowed"))?;
    }
    if files > ir.limits.generated_files {
        return Err(resource_limit(
            "semantic owner inventory exceeds the generated file limit",
        ));
    }
    Ok(())
}

fn resource_limit(message: &str) -> RenderError {
    RenderError {
        diagnostic: Diagnostic::error(DiagnosticCode::LimitExceeded, message),
    }
}
